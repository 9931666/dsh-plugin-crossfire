/**
 * 注入全局系统提示的用法段落（纯文本模块，体积可被测试断言）。
 *
 * 与圆桌会议的 `prompt.ts` 关键差异：这里**没有**主持人编排协议。圆桌要求模型
 * 按轮次统筹、转述、聚合；针锋的推进由卡片按钮经 RPC 直推 host 状态机完成，
 * 模型不是编排者。所以这段文字交代的是：针锋是什么、四条不可越界的边界、工具
 * 清单与调用顺序，以及**什么时候不该用它**。
 *
 * @module dsh-plugin-crossfire/prompt
 */

/** 七步编排与那一条不可越界的规则。 */
export const USAGE_STEPS: readonly string[] = [
  '1. `crossfire_open` —— 把待验证对象摆上台（标题 + 正文 + 维度 + 强度，可选立场）。状态 `draft`。',
  '2. `crossfire_stance`（可选但强烈建议）—— 写入"用户的立场与理由"。用户自己写最好；他没写就**从对话提炼**并传 `distilled=true`，但**绝不虚构**他没表达过的立场（虚构的立场等于给红队一个假靶子）。有了立场，每条红队缺陷都必须回应其中一条理由，并标注是否被打穿。用户随时可以在卡片上改。',
  '3. `crossfire_attack` —— 按维度拉起只读红队专家。状态 `attacking`。',
  '4. `crossfire_collect` —— 把专家发言拆成逐条可裁决的缺陷（自动过滤过程叙述、归一化维度、去掉用户上轮驳回过的重复项）。状态 `judging`。',
  '5. **等人在卡片上逐条表态**。这一步没有工具可代劳。',
  '6. `crossfire_finish` —— 定稿，把已认定缺陷固化为 known-flaws 清单并写入历史。状态 `settled`。',
  '7. `crossfire_recheck` —— 复审：只核对上一轮已认定的缺陷是否修复，**不许开新战线**；`crossfire_export` 导出 Markdown。',
]

/**
 * 当前版本的用法段落。
 */
export function usageSectionText(): string {
  return [
    '## 针锋 Crossfire（对抗式评审）',
    '',
    '针锋只做一件事：把一个**已经定稿**的成果或方案摆上台，让若干红队专家从指定维度分头攻击，把攻击拆成逐条可裁决的缺陷。',
    '',
    '四条边界（不要越界，越界即破坏了它存在的意义）：',
    '',
    '1. **表态永远由人做。** 不存在"代表认定缺陷"的工具，也不该替你认定。认定 / 驳回只能由用户在卡片上操作。',
    '2. **针锋不产出方案、不改代码、不自动修复。** 它是验收器，不是执行器。',
    '3. **红队专家只读。** 它们的工具被限制为只读检索（read / read_image / glob / grep）加一个 `crossfire_report`：只挑错，不动工作区。',
    '4. **不许把用户偏好喂给红队。** 历史表态记录只用于去重与复审递进，绝不用来塑造专家对"用户喜欢什么"的预期。',
    '',
    '### 编排（七步，每步可单独重试）',
    '',
    ...USAGE_STEPS,
    '',
    '### 什么时候该用 / 不该用',
    '',
    '- **该用**：一个方案、一段设计、一份清单**已经定稿**，你或用户想知道它在哪些地方站不住。',
    '- **该用**：需要"逐条可追溯的判断"而不是一句"看起来还行"——每条缺陷都有来源专家、维度与证据分级，用户逐条认定或驳回。',
    '- **不该用**：还处在"要做什么"的阶段。针锋不产出方案，此时应该先正常讨论再定稿。',
    '- **不该用**：需要多 agent 分工把活干完。那是协作型团队的场景；针锋的专家不写代码、不产出交付物。',
    '',
    '### 两条容易搞错的细节',
    '',
    '- `crossfire_attack` 返回之后专家**仍在跑**：它是后台子代理，`crossfire_collect` 之前请确认它们已经提交（卡片上会显示每位专家的状态）。',
    '- 用户在卡片上的表态**随时可能发生**，也可能一直不发生。不要在用户没表态时反复调用 `crossfire_finish` 催结论——未完成的清单就是未完成，那是刻意的。',
  ].join('\n')
}
